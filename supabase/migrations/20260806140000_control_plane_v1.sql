create policy runs_owner_select
  on lab_indicadores.runs for select to authenticated
  using ((select auth.uid()) = owner_id);

create policy commands_owner_select
  on lab_indicadores.commands for select to authenticated
  using ((select auth.uid()) = owner_id);

create policy commands_owner_insert
  on lab_indicadores.commands for insert to authenticated
  with check ((select auth.uid()) = owner_id);

create policy events_owner_select
  on lab_indicadores.events for select to authenticated
  using (exists (
    select 1 from lab_indicadores.runs r
    where r.id = run_id and r.owner_id = (select auth.uid())
  ));

create policy artifacts_owner_select
  on lab_indicadores.artifacts for select to authenticated
  using (exists (
    select 1 from lab_indicadores.runs r
    where r.id = run_id and r.owner_id = (select auth.uid())
  ));

create policy workers_authenticated_select
  on lab_indicadores.workers for select to authenticated
  using (true);

